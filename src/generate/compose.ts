import { stringify } from "yaml";
import type { CatalogEntry, ComposeFragment } from "../catalog/types.js";
import type { Plan } from "./plan.js";

export const NETWORK = "dock";

/** Docker Hub images get the mirror prefix; fully-qualified images are left alone. */
export function qualifyImage(image: string, registry: string): string {
  if (!registry) return image;
  if (!image.includes("/")) return `${registry}/${image}`;
  const first = image.split("/")[0]!;
  const hasHost = first.includes(".") || first.includes(":") || first === "localhost";
  return hasHost ? image : `${registry}/${image}`;
}

export interface ComposeDoc {
  name: string;
  services: Record<string, Partial<ComposeFragment> & { networks: string[]; [key: string]: unknown }>;
  volumes?: Record<string, null>;
  networks: Record<string, { name: string }>;
}

export function buildCompose(plan: Plan, project: string, registry: string): ComposeDoc {
  const services: ComposeDoc["services"] = {};
  const volumes: Record<string, null> = {};
  const runnableIds = new Set(plan.runnable.map((e) => e.id));

  for (const entry of plan.runnable) {
    const frag: ComposeFragment = structuredClone(entry.compose!);
    frag.image = qualifyImage(frag.image, registry);
    frag.restart ??= "unless-stopped";
    frag.environment = { ...providerEnv(entry, plan), ...frag.environment };
    for (const v of frag.volumes ?? []) {
      const src = v.split(":")[0]!;
      if (!src.startsWith(".") && !src.startsWith("/") && !src.startsWith("$")) volumes[src] = null;
    }
    if (frag.depends_on) frag.depends_on = filterDeps(frag.depends_on, runnableIds);
    services[entry.id] = { ...frag, networks: [NETWORK] };
  }
  const doc: ComposeDoc = { name: `${project}-dock`, services, networks: { [NETWORK]: { name: `${project}-dock` } } };
  if (Object.keys(volumes).length) doc.volumes = volumes;
  return doc;
}

export const APP_SERVICE = "app";
export const APP_PROFILE = "app";

/**
 * The project's own image, built from its Dockerfile, on the stack network. Lives behind
 * the `app` compose profile so `dock up` stays infra-only until `dock up --app`.
 * `appEnv` is the host view (localhost:port); here it is rewritten to service addresses.
 */
export function appService(plan: Plan, env: Record<string, string>, appEnv: Record<string, string>, app: { dockerfile: string; port: string }, registry = ""): ComposeDoc["services"][string] {
  const environment = internalAppEnv(plan, env, appEnv);
  const depends_on: Record<string, { condition: string }> = {};
  for (const e of plan.runnable) {
    const c = e.compose!;
    depends_on[e.id] = { condition: c.restart === "no" ? "service_completed_successfully" : c.healthcheck ? "service_healthy" : "service_started" };
  }
  return {
    // Dockerfiles may opt in with `ARG DOCK_REGISTRY=docker.io` + `FROM ${DOCK_REGISTRY}/node:22`
    build: { context: "..", dockerfile: app.dockerfile, args: { DOCK_REGISTRY: registry || "docker.io" } },
    image: `${env.COMPOSE_PROJECT_NAME ?? "dock"}-app`,
    profiles: [APP_PROFILE],
    ports: [`\${APP_PORT}:${app.port}`],
    environment: { ...environment, PORT: app.port, SERVER_PORT: app.port },
    depends_on,
    restart: "unless-stopped",
    networks: [NETWORK],
  };
}

/** localhost:<host port> -> <service>:<container port>, plus catalog-declared overrides. */
export function internalAppEnv(plan: Plan, env: Record<string, string>, appEnv: Record<string, string>): Record<string, string> {
  const portMap = new Map<string, string>();
  for (const e of plan.runnable) {
    for (const p of e.compose?.ports ?? []) {
      const [host, container] = p.split(":");
      const hostPort = host!.replace(/\$\{(\w+)\}/g, (_, k) => env[k] ?? "");
      if (hostPort && container) portMap.set(`localhost:${hostPort}`, `${e.id}:${container}`);
    }
  }
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(appEnv)) {
    out[k] = v.replace(/localhost:\d+/g, (m) => portMap.get(m) ?? m);
  }
  for (const e of [...plan.selected, ...plan.runnable]) {
    for (const [k, v] of Object.entries(e.appEnvInternal ?? {})) out[k] = v.replace(/\$\{(\w+)\}/g, (_, key) => env[key] ?? "");
  }
  return out;
}

export function composeYaml(doc: ComposeDoc): string {
  const header = "# Generated by dock-local. Re-run `dock init` to regenerate; edit .dock/.env for values.\n";
  return header + stringify(doc, { lineWidth: 0 });
}

/** Providers learn what they emulate from their consumers (e.g. ministack SERVICES). */
function providerEnv(entry: CatalogEntry, plan: Plan): Record<string, string> {
  const consumers = plan.consumers.get(entry.id);
  if (!consumers?.length || !entry.providerEnvKey) return {};
  const values = [...new Set(consumers.map((c) => c.providerValue).filter(Boolean))] as string[];
  return values.length ? { [entry.providerEnvKey]: values.join(",") } : {};
}

function filterDeps(deps: ComposeFragment["depends_on"], ids: Set<string>): ComposeFragment["depends_on"] {
  if (Array.isArray(deps)) return deps.filter((d) => ids.has(d));
  return Object.fromEntries(Object.entries(deps ?? {}).filter(([d]) => ids.has(d)));
}
